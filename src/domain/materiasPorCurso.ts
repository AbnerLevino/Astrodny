// Monta a grade final do curso: comum + específicas do template + os 3
// fechamentos com o nome do curso. Curso sem template cadastrado -> [].
export function materiasDoCurso(curso: string): string[] {
  const template = TEMPLATE_DO_CURSO[curso]
  if (!template) return []

  return [
    ...COMUM,
    ...TEMPLATES[template],
    `Tópicos Avançados em ${curso}`,
    `Projeto Integrador e Prática em ${curso}`,
    `Estágio Curricular Supervisionado em ${curso}`,
  ]
}
